/* Builds sitemap.xml from the prerendered pages.

   Which routes are listed is decided by the pages themselves: a page whose
   robots meta says noindex (the not-found page, and any unlaunched product)
   is left out, so the sitemap cannot list a URL that tells search engines not
   to index it. Nothing is maintained by hand. */

import { SITE } from './routes.mjs';

/* changefreq / priority by kind of page. */
function hints(route) {
  if (route === '/') return ['weekly', '1.0'];
  if (['/services', '/products', '/industries'].includes(route)) return ['weekly', '0.9'];
  if (['/about', '/contact', '/case-studies'].includes(route)) return ['monthly', '0.8'];
  if (route.startsWith('/case-studies/')) return ['monthly', '0.6'];
  if (['/privacy', '/terms', '/cookies', '/disclaimer'].includes(route)) return ['yearly', '0.3'];
  if (['/services/animation', '/services/martech', '/services/marketing'].includes(route)) return ['monthly', '0.7'];
  return ['monthly', '0.8']; // the other service pages and the live products
}

const GROUPS = [
  ['Core', (r) => ['/', '/about', '/contact', '/industries'].includes(r)],
  ['Services', (r) => r.startsWith('/services')],
  ['Products', (r) => r.startsWith('/products')],
  ['Case studies', (r) => r.startsWith('/case-studies')],
  ['Legal', (r) => ['/privacy', '/terms', '/cookies', '/disclaimer'].includes(r)],
];

/* pages: [{ route, noindex }]   lastmod: { [route]: 'YYYY-MM-DD' } */
export function buildSitemap(pages, lastmod) {
  const listed = pages.filter((p) => !p.noindex).map((p) => p.route);
  const placed = new Set();

  const blocks = GROUPS.map(([label, test]) => {
    const rows = listed
      .filter((r) => !placed.has(r) && test(r))
      .map((route) => {
        placed.add(route);
        const [freq, prio] = hints(route);
        const loc = route === '/' ? `${SITE}/` : `${SITE}${route}`;
        const mod = lastmod[route] ? `<lastmod>${lastmod[route]}</lastmod>` : '';
        return `  <url><loc>${loc}</loc>${mod}<changefreq>${freq}</changefreq><priority>${prio}</priority></url>`;
      });
    return rows.length ? `  <!-- ── ${label} ── -->\n${rows.join('\n')}` : '';
  }).filter(Boolean);

  const leftover = listed.filter((r) => !placed.has(r));
  if (leftover.length) {
    throw new Error(`Sitemap has no group for: ${leftover.join(', ')} - add one to GROUPS in scripts/lib/sitemap.mjs.`);
  }

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/prerender.mjs at build time - do not edit. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    '',
    blocks.join('\n\n'),
    '',
    '</urlset>',
    '',
  ].join('\n');
}
